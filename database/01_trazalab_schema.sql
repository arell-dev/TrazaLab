/* Solo usuarios activos pueden registrar incidencias. */
CREATE OR REPLACE FUNCTION fn_validar_usuario_incidencia()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_estado VARCHAR(15);
BEGIN
    SELECT estado
      INTO v_estado
      FROM usuario
     WHERE usuario_id = NEW.usuario_id;

    IF v_estado IS NULL THEN
        RAISE EXCEPTION 'El usuario % no existe.', NEW.usuario_id;
    END IF;

    IF v_estado <> 'activo' THEN
        RAISE EXCEPTION 'El usuario % está inactivo y no puede registrar incidencias.', NEW.usuario_id;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_usuario_incidencia ON incidencia;
CREATE TRIGGER trg_validar_usuario_incidencia
BEFORE INSERT OR UPDATE OF usuario_id ON incidencia
FOR EACH ROW
EXECUTE FUNCTION fn_validar_usuario_incidencia();

/* Reglas de mantenimiento:
       - usuario activo
       - usuario con rol técnico
       - correctivo requiere una falla
       - si se informa falla, debe pertenecer a la misma computadora
*/
CREATE OR REPLACE FUNCTION fn_validar_mantenimiento()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_estado_usuario VARCHAR(15);
    v_rol_nombre     VARCHAR(60);
    v_computadora_falla INTEGER;
BEGIN
    SELECT u.estado, r.nombre
      INTO v_estado_usuario, v_rol_nombre
      FROM usuario u
      JOIN rol r ON r.rol_id = u.rol_id
     WHERE u.usuario_id = NEW.usuario_id;

    IF v_estado_usuario IS NULL THEN
        RAISE EXCEPTION 'El usuario % no existe o no tiene rol asignado.', NEW.usuario_id;
    END IF;

    IF v_estado_usuario <> 'activo' THEN
        RAISE EXCEPTION 'El usuario % está inactivo y no puede registrar mantenimiento.', NEW.usuario_id;
    END IF;

    IF v_rol_nombre NOT IN ('Técnico de Soporte', 'Técnico de Laboratorio') THEN
        RAISE EXCEPTION
            'El usuario % debe tener un rol técnico para registrar mantenimiento. Rol actual: %.',
            NEW.usuario_id, v_rol_nombre;
    END IF;

    IF NEW.tipo = 'correctivo' AND NEW.falla_id IS NULL THEN
        RAISE EXCEPTION 'Un mantenimiento correctivo debe estar asociado a una falla.';
    END IF;

    IF NEW.falla_id IS NOT NULL THEN
        SELECT i.computadora_id
          INTO v_computadora_falla
          FROM falla f
          JOIN incidencia i ON i.incidencia_id = f.incidencia_id
         WHERE f.falla_id = NEW.falla_id;

        IF v_computadora_falla IS NULL THEN
            RAISE EXCEPTION 'La falla % no existe o no está asociada a una incidencia válida.', NEW.falla_id;
        END IF;

        IF v_computadora_falla <> NEW.computadora_id THEN
            RAISE EXCEPTION
                'La falla % pertenece a la computadora %, pero el mantenimiento indica la computadora %.',
                NEW.falla_id, v_computadora_falla, NEW.computadora_id;
        END IF;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_mantenimiento ON mantenimiento;
CREATE TRIGGER trg_validar_mantenimiento
BEFORE INSERT OR UPDATE OF computadora_id, falla_id, usuario_id, tipo
ON mantenimiento
FOR EACH ROW
EXECUTE FUNCTION fn_validar_mantenimiento();

