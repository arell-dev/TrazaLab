    i.fecha_registro AS fecha_incidencia,
    i.estado AS estado_incidencia,
    i.descripcion AS descripcion_incidencia,
    fi.falla_id,
    fi.fecha_registro AS fecha_falla,
    tf.nombre AS tipo_falla,
    cf.nombre AS categoria_falla,
    fi.descripcion_tecnica,
    NULL::INTEGER AS mantenimiento_id,
    NULL::TIMESTAMP AS fecha_mantenimiento,
    NULL::VARCHAR(15) AS tipo_mantenimiento,
    NULL::TEXT AS descripcion_mantenimiento,
    NULL::TEXT AS tecnico_responsable
FROM computadora c
JOIN ubicacion ubl
  ON ubl.ubicacion_id = c.ubicacion_id
LEFT JOIN incidencia i
  ON i.computadora_id = c.computadora_id
LEFT JOIN falla fi
  ON fi.incidencia_id = i.incidencia_id
LEFT JOIN tipo_falla tf
  ON tf.tipo_falla_id = fi.tipo_falla_id
LEFT JOIN categoria_falla cf
  ON cf.categoria_falla_id = tf.categoria_falla_id
UNION ALL
SELECT
    c.computadora_id,
    c.codigo_qr,
    c.numero_serie,
    c.marca,
    c.modelo,
    ubl.nombre AS ubicacion,
    NULL::INTEGER AS incidencia_id,
    NULL::TIMESTAMP AS fecha_incidencia,
    NULL::VARCHAR(15) AS estado_incidencia,
    NULL::TEXT AS descripcion_incidencia,
    NULL::INTEGER AS falla_id,
    NULL::TIMESTAMP AS fecha_falla,
    NULL::VARCHAR(80) AS tipo_falla,
    NULL::VARCHAR(60) AS categoria_falla,
    NULL::TEXT AS descripcion_tecnica,
    m.mantenimiento_id,
    m.fecha AS fecha_mantenimiento,
    m.tipo AS tipo_mantenimiento,
    m.descripcion AS descripcion_mantenimiento,
    CONCAT(us.nombres, ' ', us.apellidos) AS tecnico_responsable
FROM computadora c
JOIN ubicacion ubl
  ON ubl.ubicacion_id = c.ubicacion_id
JOIN mantenimiento m
  ON m.computadora_id = c.computadora_id
JOIN usuario us
  ON us.usuario_id = m.usuario_id;

CREATE OR REPLACE VIEW vw_fallas_recurrentes AS
SELECT
    c.computadora_id,
    c.codigo_qr,
    c.numero_serie,
    cf.nombre AS categoria_falla,
    tf.tipo_falla_id,
    tf.nombre AS tipo_falla,
    COUNT(*) AS frecuencia,
    MAX(f.fecha_registro) AS ultima_identificacion
FROM falla f
JOIN incidencia i
  ON i.incidencia_id = f.incidencia_id
JOIN computadora c
  ON c.computadora_id = i.computadora_id
JOIN tipo_falla tf
  ON tf.tipo_falla_id = f.tipo_falla_id
JOIN categoria_falla cf
  ON cf.categoria_falla_id = tf.categoria_falla_id
GROUP BY
    c.computadora_id,
    c.codigo_qr,
    c.numero_serie,
    cf.nombre,
    tf.tipo_falla_id,
    tf.nombre
HAVING COUNT(*) > 1;

CREATE OR REPLACE VIEW vw_componentes_por_mantenimiento AS
SELECT
    m.mantenimiento_id,
    m.fecha,
    m.tipo AS tipo_mantenimiento,
    c.computadora_id,
    c.codigo_qr,
    c.numero_serie,
    comp.componente_id,
    comp.nombre AS componente,
    comp.tipo AS tipo_componente,
    comp.numero_serie AS serie_componente,
    mc.accion,
    mc.cantidad,
    CONCAT(u.nombres, ' ', u.apellidos) AS tecnico_responsable
FROM mantenimiento_componente mc
JOIN mantenimiento m
  ON m.mantenimiento_id = mc.mantenimiento_id
JOIN computadora c
  ON c.computadora_id = m.computadora_id
JOIN componente comp
  ON comp.componente_id = mc.componente_id
JOIN usuario u
  ON u.usuario_id = m.usuario_id;

/* Composición actual para la ficha de computadora e indicadores de hardware. */
CREATE OR REPLACE VIEW vw_componentes_actuales AS
SELECT
    cc.computadora_id,
    c.codigo_qr,
    c.numero_serie AS serie_computadora,
    comp.componente_id,
    comp.nombre AS componente,
    comp.tipo AS tipo_componente,
    comp.numero_serie AS serie_componente,
    cc.fecha_instalacion
FROM computadora_componente cc
JOIN computadora c
  ON c.computadora_id = cc.computadora_id
JOIN componente comp
  ON comp.componente_id = cc.componente_id
WHERE cc.fecha_retiro IS NULL;

