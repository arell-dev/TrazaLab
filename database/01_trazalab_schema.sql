    computadora_id   INTEGER NOT NULL,
    componente_id    INTEGER NOT NULL,
    fecha_instalacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_retiro     TIMESTAMP,

    CONSTRAINT pk_computadora_componente
        PRIMARY KEY (computadora_id, componente_id, fecha_instalacion),
    CONSTRAINT fk_computadora_componente_computadora
        FOREIGN KEY (computadora_id)
        REFERENCES computadora (computadora_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT fk_computadora_componente_componente
        FOREIGN KEY (componente_id)
        REFERENCES componente (componente_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    CONSTRAINT ck_computadora_componente_fechas
        CHECK (fecha_retiro IS NULL OR fecha_retiro >= fecha_instalacion)
);

/* Historial de servicio. Una pieza individual solo puede tener una
   computadora asignada actualmente. */
CREATE UNIQUE INDEX IF NOT EXISTS uq_componente_asignacion_actual
    ON computadora_componente (componente_id)
    WHERE fecha_retiro IS NULL;

/* Impide que el historial asigne una pieza a dos equipos durante periodos
   que se superponen. Un retiro y una nueva instalación pueden compartir hora. */
CREATE OR REPLACE FUNCTION fn_validar_periodo_componente()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF EXISTS (
        SELECT 1
          FROM computadora_componente cc
         WHERE cc.componente_id = NEW.componente_id
           AND NOT (
               TG_OP = 'UPDATE'
               AND cc.computadora_id = OLD.computadora_id
               AND cc.componente_id = OLD.componente_id
               AND cc.fecha_instalacion = OLD.fecha_instalacion
           )
           AND cc.fecha_instalacion < COALESCE(NEW.fecha_retiro, 'infinity'::TIMESTAMP)
           AND COALESCE(cc.fecha_retiro, 'infinity'::TIMESTAMP) > NEW.fecha_instalacion
    ) THEN
        RAISE EXCEPTION
            'El componente % ya tiene una asignación a una computadora en ese periodo.',
            NEW.componente_id;
    END IF;

    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_validar_periodo_componente ON computadora_componente;
CREATE TRIGGER trg_validar_periodo_componente
BEFORE INSERT OR UPDATE OF computadora_id, componente_id, fecha_instalacion, fecha_retiro
ON computadora_componente
FOR EACH ROW
EXECUTE FUNCTION fn_validar_periodo_componente();

