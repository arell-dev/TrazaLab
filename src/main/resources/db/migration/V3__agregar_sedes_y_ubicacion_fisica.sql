CREATE TABLE sede (
    sede_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    nombre VARCHAR(100) NOT NULL,

    CONSTRAINT pk_sede PRIMARY KEY (sede_id),
    CONSTRAINT uq_sede_nombre UNIQUE (nombre),
    CONSTRAINT ck_sede_nombre_no_vacio CHECK (btrim(nombre) <> '')
);

INSERT INTO sede (nombre)
VALUES ('UTP Sede Piura')
ON CONFLICT (nombre) DO NOTHING;

ALTER TABLE ubicacion
    ADD COLUMN sede_id INTEGER,
    ADD COLUMN edificio VARCHAR(80),
    ADD COLUMN piso INTEGER,
    ADD COLUMN tipo VARCHAR(20) NOT NULL DEFAULT 'LABORATORIO';

UPDATE ubicacion
SET sede_id = (SELECT sede_id FROM sede WHERE nombre = 'UTP Sede Piura'),
    edificio = CASE WHEN UPPER(nombre) = 'LAB-01' THEN 'Torre A' ELSE edificio END,
    piso = CASE WHEN UPPER(nombre) = 'LAB-01' THEN 3 ELSE piso END,
    detalle = CASE WHEN UPPER(nombre) = 'LAB-01' THEN 'Cómputo General' ELSE detalle END,
    tipo = CASE WHEN UPPER(nombre) = 'LAB-01' THEN 'LABORATORIO' ELSE tipo END;

ALTER TABLE ubicacion
    ALTER COLUMN sede_id SET NOT NULL,
    ADD CONSTRAINT fk_ubicacion_sede
        FOREIGN KEY (sede_id)
        REFERENCES sede (sede_id)
        ON UPDATE CASCADE
        ON DELETE RESTRICT,
    ADD CONSTRAINT ck_ubicacion_piso_positivo
        CHECK (piso IS NULL OR piso > 0),
    ADD CONSTRAINT ck_ubicacion_tipo
        CHECK (tipo IN ('TORRE', 'PISO', 'AULA', 'LABORATORIO', 'OTRO'));

CREATE INDEX idx_ubicacion_sede_fisica
    ON ubicacion (sede_id, edificio, piso, nombre);

INSERT INTO ubicacion (nombre, detalle, sede_id, edificio, piso, tipo)
SELECT ubicacion_nueva.nombre,
       ubicacion_nueva.detalle,
       sede.sede_id,
       ubicacion_nueva.edificio,
       ubicacion_nueva.piso,
       ubicacion_nueva.tipo
FROM (VALUES
    ('LAB-01', 'Cómputo General', 'Torre A', 3, 'LABORATORIO'),
    ('LAB-02', 'Redes y Telecom', 'Torre A', 3, 'LABORATORIO'),
    ('LAB-03', 'Arquitectura de Software', 'Torre A', 3, 'LABORATORIO'),
    ('LAB-07', 'Inteligencia Artificial', 'Torre A', 4, 'LABORATORIO')
) AS ubicacion_nueva(nombre, detalle, edificio, piso, tipo)
CROSS JOIN sede
WHERE sede.nombre = 'UTP Sede Piura'
    AND NOT EXISTS (
        SELECT 1
        FROM ubicacion existente
        WHERE existente.sede_id = sede.sede_id
            AND UPPER(existente.nombre) = UPPER(ubicacion_nueva.nombre)
    );
